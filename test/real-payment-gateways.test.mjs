// TEST 2: RAZORPAY CRYPTOGRAPHIC HMAC-SHA256 SIGNATURE VERIFICATION
// ----------------------------------------------------
test("Gateway Verification: Razorpay HMAC-SHA256 Signature", () => {
  const secret = "test_razorpay_secret_key_12345";
  const orderId = "order_Oq7Jk8Lm9NpQ";
  const paymentId = "pay_Pq8Rk9Lm0NqR";

  // Legitimate signature generated by Razorpay PG
  const legitimateSignature = crypto
    .createHmac("sha256", secret)
    .update(`${orderId}|${paymentId}`)
    .digest("hex");

  const verifyRazorpaySignature = (ordId, payId, sig, sec) => {
    const computed = crypto.createHmac("sha256", sec).update(`${ordId}|${payId}`).digest("hex");
    return computed === sig;
  };

  assert.equal(verifyRazorpaySignature(orderId, paymentId, legitimateSignature, secret), true);

  // Tampered payment ID must be rejected
  const tamperedPaymentId = "pay_TAMPERED_0000";
  assert.equal(verifyRazorpaySignature(orderId, tamperedPaymentId, legitimateSignature, secret), false);

  // Wrong secret must fail
  assert.equal(verifyRazorpaySignature(orderId, paymentId, legitimateSignature, "wrong_secret"), false);
});

