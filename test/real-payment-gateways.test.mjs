// TEST 7: NO DUPLICATE PAYMENTS & IDEMPOTENCY ENFORCEMENT
// ----------------------------------------------------
test("Payment Engine: Idempotency & Duplicate Prevention", () => {
  const processedTransactions = new Set();

  const processPaymentCommit = (transactionId) => {
    if (processedTransactions.has(transactionId)) {
      return { isDuplicate: true, status: "already_confirmed" };
    }
    processedTransactions.add(transactionId);
    return { isDuplicate: false, status: "confirmed" };
  };

  const txn1 = processPaymentCommit("TXN_GATEWAY_SESSION_9821");
  assert.equal(txn1.isDuplicate, false);
  assert.equal(txn1.status, "confirmed");

  // Re-submission of the same payment intent / transaction ID must be idempotent
  const txn2 = processPaymentCommit("TXN_GATEWAY_SESSION_9821");
  assert.equal(txn2.isDuplicate, true);
  assert.equal(txn2.status, "already_confirmed");
});

