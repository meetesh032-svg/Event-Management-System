// TEST 3: PAYU OFFICIAL SHA-512 REQUEST & RESPONSE HASHING
// ----------------------------------------------------
test("Gateway Verification: PayU SHA-512 Request Hash & Response Reverse Hash", () => {
  const key = "test_payu_merchant_key";
  const salt = "test_payu_merchant_salt";
  const txnid = "txnid_ORD17293817_4412";
  const amount = "535.40";
  const productinfo = "Coldplay Music of the Spheres";
  const firstname = "Aarav";
  const email = "aarav@example.com";

  // Request Hash Formula: sha512(key|txnid|amount|productinfo|firstname|email|udf1|udf2|udf3|udf4|udf5||||||SALT)
  const reqHashString = `${key}|${txnid}|${amount}|${productinfo}|${firstname}|${email}|||||||||||${salt}`;
  const requestHash = crypto.createHash("sha512").update(reqHashString).digest("hex");
  assert.ok(requestHash && requestHash.length === 128);

  // Response Hash Formula: sha512(SALT|status||||||udf5|udf4|udf3|udf2|udf1|email|firstname|productinfo|amount|txnid|key)
  const status = "success";
  const respHashString = `${salt}|${status}|||||||||||${email}|${firstname}|${productinfo}|${amount}|${txnid}|${key}`;
  const responseHash = crypto.createHash("sha512").update(respHashString).digest("hex");

  const verifyPayUResponse = (recStatus, recTxn, recAmt, recProd, recFirst, recEmail, recKey, recSalt, recHash) => {
    const comp = crypto
      .createHash("sha512")
      .update(`${recSalt}|${recStatus}|||||||||||${recEmail}|${recFirst}|${recProd}|${recAmt}|${recTxn}|${recKey}`)
      .digest("hex");
    return comp.toLowerCase() === recHash.toLowerCase();
  };

  assert.equal(
    verifyPayUResponse(status, txnid, amount, productinfo, firstname, email, key, salt, responseHash),
    true
  );

  // Tampered response status or amount must be rejected
  assert.equal(
    verifyPayUResponse("failure", txnid, amount, productinfo, firstname, email, key, salt, responseHash),
    false
  );
  assert.equal(
    verifyPayUResponse(status, txnid, "1.00", productinfo, firstname, email, key, salt, responseHash),
    false
  );
});

