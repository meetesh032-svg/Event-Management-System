test("Gateway Verification: Cashfree Timestamped HMAC-SHA256 Webhook", () => {
  const secretKey = "test_cashfree_secret_key_8812";
  const timestamp = "1729384910283";
  const rawBody = JSON.stringify({
    type: "PAYMENT_SUCCESS_WEBHOOK",
    data: {
      order: { order_id: "ORD-98214", order_amount: 535.40 },
      payment: { cf_payment_id: 1029384, payment_status: "SUCCESS" },
    },
  });

  const signature = crypto
    .createHmac("sha256", secretKey)
    .update(`${timestamp}${rawBody}`)
    .digest("base64");

  const verifyCashfreeWebhook = (ts, body, sec, sig) => {
    const computed = crypto.createHmac("sha256", sec).update(`${ts}${body}`).digest("base64");
    return computed === sig;
  };

  assert.equal(verifyCashfreeWebhook(timestamp, rawBody, secretKey, signature), true);
  assert.equal(verifyCashfreeWebhook(timestamp, rawBody, "wrong_secret", signature), false);
});

