// TEST 5: PHONEPE OFFICIAL SHA-256 BASE64 CHECKSUM VERIFICATION
// ----------------------------------------------------
test("Gateway Verification: PhonePe SHA-256 Base64 Checksum", () => {
  const saltKey = "099eb0cd-02cf-4e2a-8aca-3e6c6aff0399";
  const saltIndex = "1";
  const payloadObj = {
    merchantId: "PGTESTPAYUAT",
    merchantTransactionId: "PP_ORD1234_9921",
    amount: 53540,
    redirectUrl: "http://localhost:3000/bookings/success",
    paymentInstrument: { type: "PAY_PAGE" },
  };

  const base64Payload = Buffer.from(JSON.stringify(payloadObj)).toString("base64");
  const stringToHash = `${base64Payload}/pg/v1/pay${saltKey}`;
  const sha256Hash = crypto.createHash("sha256").update(stringToHash).digest("hex");
  const expectedXVerify = `${sha256Hash}###${saltIndex}`;

  const verifyPhonePeXVerify = (base64, endpoint, salt, index, receivedXVerify) => {
    const hash = crypto.createHash("sha256").update(`${base64}${endpoint}${salt}`).digest("hex");
    return `${hash}###${index}` === receivedXVerify;
  };

  assert.equal(
    verifyPhonePeXVerify(base64Payload, "/pg/v1/pay", saltKey, saltIndex, expectedXVerify),
    true
  );

  // Tampered endpoint or payload fails
  assert.equal(
    verifyPhonePeXVerify(base64Payload, "/pg/v1/status", saltKey, saltIndex, expectedXVerify),
    false
  );
});

