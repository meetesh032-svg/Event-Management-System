// TEST 4: CCAVENUE OFFICIAL AES-128-CBC ENCRYPTION & DECRYPTION
// ----------------------------------------------------
test("Gateway Verification: CCAvenue AES-128-CBC Encryption & Decryption", () => {
  const workingKey = "4E5C4E1D3F8B7A9A2C1B0D8E7F6A5B4C";
  const CCAVENUE_IV = Buffer.from([
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
    0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
  ]);

  const encryptCCAvenue = (plainText, keyStr) => {
    const m = crypto.createHash("md5").update(keyStr).digest();
    const cipher = crypto.createCipheriv("aes-128-cbc", m, CCAVENUE_IV);
    let enc = cipher.update(plainText, "utf8", "hex");
    enc += cipher.final("hex");
    return enc;
  };

  const decryptCCAvenue = (encHex, keyStr) => {
    const m = crypto.createHash("md5").update(keyStr).digest();
    const decipher = crypto.createDecipheriv("aes-128-cbc", m, CCAVENUE_IV);
    let dec = decipher.update(encHex, "hex", "utf8");
    dec += decipher.final("utf8");
    return dec;
  };

  const samplePayload = "order_id=CCAV_102938&order_status=Success&amount=535.40&tracking_id=310294857102&bank_ref_no=HDFC98214";
  const encrypted = encryptCCAvenue(samplePayload, workingKey);
  assert.ok(encrypted && encrypted.length > 0);

  const decrypted = decryptCCAvenue(encrypted, workingKey);
  assert.equal(decrypted, samplePayload);

  const params = new URLSearchParams(decrypted);
  assert.equal(params.get("order_status"), "Success");
  assert.equal(params.get("tracking_id"), "310294857102");
  assert.equal(params.get("amount"), "535.40");
});

