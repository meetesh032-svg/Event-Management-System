// TEST 1: BACKEND FEE & GRAND TOTAL CALCULATION
// ----------------------------------------------------
test("Payment Engine: Backend Grand Total Calculation", () => {
  const calculateFeeBreakdown = ({
    subtotalCents,
    discountCents = 0,
    promotionDiscountCents = 0,
    walletBalanceCents = 0,
    useWallet = false,
  }) => {
    const totalDiscounts = discountCents + promotionDiscountCents;
    const discountedBase = Math.max(0, subtotalCents - totalDiscounts);

    const platformFeeCents = subtotalCents > 0 ? 500 : 0; // ₹5.00
    const convenienceFeeCents = subtotalCents > 0 ? 2500 : 0; // ₹25.00
    const taxesCents = subtotalCents > 0 ? Math.round(((platformFeeCents + convenienceFeeCents) * 18) / 100) : 0;

    const payableBeforeWallet = discountedBase + platformFeeCents + convenienceFeeCents + taxesCents;
    const walletDeductionCents = useWallet && walletBalanceCents > 0 ? Math.min(payableBeforeWallet, walletBalanceCents) : 0;
    const totalAmountCents = Math.max(0, payableBeforeWallet - walletDeductionCents);

    return {
      subtotalCents,
      platformFeeCents,
      convenienceFeeCents,
      taxesCents,
      discountCents,
      promotionDiscountCents,
      walletDeductionCents,
      totalAmountCents,
    };
  };

  // 1. Standard ₹500 ticket (50000 paise)
  const calc1 = calculateFeeBreakdown({ subtotalCents: 50000 });
  assert.equal(calc1.subtotalCents, 50000);
  assert.equal(calc1.platformFeeCents, 500);
  assert.equal(calc1.convenienceFeeCents, 2500);
  assert.equal(calc1.taxesCents, 540); // 18% of ₹30 (₹5.40 = 540 paise)
  assert.equal(calc1.totalAmountCents, 53540); // ₹535.40

  // 2. With ₹100 Coupon Discount (10000 paise)
  const calc2 = calculateFeeBreakdown({ subtotalCents: 50000, discountCents: 10000 });
  assert.equal(calc2.totalAmountCents, 43540); // ₹435.40

  // 3. With Wallet Balance Deduction
  const calc3 = calculateFeeBreakdown({
    subtotalCents: 50000,
    discountCents: 10000,
    walletBalanceCents: 20000,
    useWallet: true,
  });
  assert.equal(calc3.walletDeductionCents, 20000);
  assert.equal(calc3.totalAmountCents, 23540); // ₹235.40

  // 4. Free ticket (₹0)
  const calcFree = calculateFeeBreakdown({ subtotalCents: 0 });
  assert.equal(calcFree.platformFeeCents, 0);
  assert.equal(calcFree.convenienceFeeCents, 0);
  assert.equal(calcFree.taxesCents, 0);
  assert.equal(calcFree.totalAmountCents, 0);
});

