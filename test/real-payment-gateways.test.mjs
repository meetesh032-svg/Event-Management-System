// TEST 8: SEAT RESERVATION HOLD TTL & AUTOMATIC RELEASE
// ----------------------------------------------------
test("Booking Engine: Temporary Seat Reservation TTL & Auto-Release", () => {
  const seats = [
    { seatNumber: "A-1", status: "held", heldUntil: new Date(Date.now() - 5000) }, // Expired
    { seatNumber: "A-2", status: "held", heldUntil: new Date(Date.now() + 600000) }, // Valid hold
    { seatNumber: "A-3", status: "booked", heldUntil: null }, // Booked
  ];

  const releaseExpiredSeats = (seatList) => {
    const now = new Date();
    return seatList.map((s) => {
      if (s.status === "held" && s.heldUntil && s.heldUntil < now) {
        return { ...s, status: "released", heldUntil: null };
      }
      return s;
    });
  };

  const updatedSeats = releaseExpiredSeats(seats);
  assert.equal(updatedSeats[0].status, "released");
  assert.equal(updatedSeats[1].status, "held");
  assert.equal(updatedSeats[2].status, "booked");
});
